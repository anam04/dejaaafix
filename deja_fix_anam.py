import json, os, re, sqlite3, time, uuid

DB = os.environ.get("DEJA_DB", "dejafix.db")
BIG_MODEL = os.environ.get("MODEL_BIG", "gemini-3.5-flash-lite")     # used for escalation
SMALL_MODEL = os.environ.get("MODEL_SMALL", "gemini-3.5-flash-lite")  # used for everything else
